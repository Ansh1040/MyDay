/** What we know about a source, gathered from the catalog and your own data. */
export interface RemixSource {
  ref: Ref;
  title: string;
  text: string; // a short body/summary used inside templates
  topics: string[];
  kindLabel: string;
  area: Area;
  format?: FormatKey;
  minutes?: number;
  energy?: Energy;
  comfort?: Comfort;
  cost?: Cost;
  social?: Social;
  /** Source-specific ideas: a skill's real-world uses, a rabbit node's branches, perspective lenses… */
  extras: string[];
  question?: string;
  skillId?: string;
}

const clean = (s: string) => s.replace(/\s+/g, ' ').trim();

function firstSentence(text: string, max = 160): string {
  const t = clean(text);
  if (!t) return '';
  const m = t.match(/^(.+?[.!?])(\s|$)/);
  const s = m ? m[1] : t;
  return s.length > max ? s.slice(0, max - 1).replace(/\s+\S*$/, '') + '…' : s;
}

function shorten(title: string, max = 48): string {
  const t = clean(title).replace(/[.:;,]+$/, '');
  if (t.length <= max) return t;
  return t.slice(0, max).replace(/\s+\S*$/, '') + '…';
}

/** Resolve a Ref into a remix source. Returns null for things that can't be remixed (or no longer exist). */
export function remixSource(ref: Ref): RemixSource | null {
  const s = useStore.getState();
  switch (ref.kind) {
    case 'experience': {
      const e = getExperience(ref.id);
      if (!e) return null;
      let text = e.summary;
      const p = e.payload as { sections?: { text?: string }[]; prompt?: string; question?: string } | null;
      if (!text && p?.sections?.[0]?.text) text = p.sections[0].text;
      if (!text && p?.prompt) text = p.prompt;
      return {
        ref, title: e.title, text: text ?? '', topics: e.topics, kindLabel: 'Experience', area: e.area === 'history' ? 'general' : e.area,
        format: e.format, minutes: e.minutes, energy: e.energy, comfort: e.comfort, cost: e.cost, social: e.social,
        extras: e.followUps ?? [], question: p?.question, skillId: e.skillId,
      };
    }
    case 'rabbit': {
      const r = getRabbitHole(ref.id);
      if (!r) return null;
      const start = r.nodes.find((n) => n.id === r.start);
      return { ref, title: r.title, text: r.hook, topics: r.topics, kindLabel: 'Rabbit hole', area: 'rabbit', extras: start?.branches.map((b) => b.label) ?? [], question: start?.question };
    }
    case 'rabbitNode': {
      const [rid, nid] = ref.id.split('/');
      const r = getRabbitHole(rid);
      const n = r?.nodes.find((x) => x.id === nid);
      if (!r || !n) return null;
      return {
        ref, title: n.title, text: n.question ?? n.body, topics: r.topics, kindLabel: 'Rabbit-hole idea', area: 'rabbit',
        extras: [...n.branches.map((b) => b.label), ...(n.perspectives?.map((p) => p.lens) ?? [])], question: n.question,
      };
    }
    case 'skill': {
      const k = getSkill(ref.id);
      if (!k) return null;
      return { ref, title: k.name, text: k.tagline, topics: k.topics, kindLabel: 'Skill', area: 'skill', extras: k.realWorld, skillId: k.id };
    }
    case 'note': {
      const n = s.notes[ref.id];
      if (!n) return null;
      const title = n.title || firstSentence(n.text, 60) || (n.kind === 'link' && n.url ? n.url : 'Untitled note');
      return { ref, title, text: n.text, topics: n.topics, kindLabel: 'Field note', area: 'general', extras: [] };
    }
    case 'entry': {
      const e = s.entries[ref.id];
      if (!e) return null;
      return { ref, title: e.title || firstSentence(e.text, 60) || 'Untitled entry', text: e.text, topics: e.topics, kindLabel: 'Version History', area: 'history', extras: e.before ? [e.before] : [] };
    }
    case 'twist': {
      const t = s.twists[ref.id];
      if (!t) return null;
      return {
        ref, title: t.text, text: t.reflection ?? t.text, topics: t.topics, kindLabel: 'Plot twist', area: 'twist',
        minutes: t.minutes, energy: t.energy, comfort: t.comfort, cost: t.cost, social: t.social, extras: [],
      };
    }
    case 'perspective': {
      const p = getPerspective(ref.id);
      if (!p) return null;
      return { ref, title: p.question, text: p.question, topics: p.topics, kindLabel: 'Perspective question', area: 'general', extras: p.lenses.map((l) => l.name), question: p.question };
    }
    case 'topic': {
      const t = TOPICS.find((x) => x.id === ref.id);
      if (!t) return null;
      return { ref, title: t.label, text: t.blurb, topics: [t.id], kindLabel: 'Topic', area: 'general', extras: [] };
    }
    default:
      // Capsules (sealed contents), collections and quests are not remixable.
      return null;
  }
}

/** Transformations that make sense for a source. */
export function remixOptions(source: Ref): RemixOption[] {
  let ids: RemixTransform[] = [];
  switch (source.kind) {
    case 'experience': {
      const f = remixSource(source)?.format;
      ids = ['experiment', 'quiz', 'challenge'];
      // Don't offer "turn an experiment into an experiment".
      const filtered = ids.filter((id) => REMIX_OPTIONS[id].format !== f);
      if (filtered.length >= 2) ids = filtered;
      // A story or a letter is a different piece from a writing prompt, so writing sources keep both; only a debate drops debate.
      if (f === 'reflection' || f === 'writing' || f === 'debate') ids = ['story', 'letter', ...(f === 'debate' ? [] : ['debate' as const]), ...ids];
      break;
    }
    case 'entry': ids = ['story', 'letter', 'debate']; break;
    case 'skill': ids = ['realworld', 'project']; break;
    case 'rabbit':
    case 'rabbitNode': ids = ['creative', 'outdoor', 'quiz']; break;
    case 'note': ids = ['experiment', 'prompt']; break;
    case 'twist': ids = ['duo']; break;
    case 'perspective': ids = ['debate', 'letter']; break;
    case 'topic': ids = ['experiment', 'outdoor', 'creative']; break;
    default: ids = [];
  }
  return ids.map((id) => REMIX_OPTIONS[id]);
}

// ---------- template machinery ----------
type Vars = Record<string, string>;
const fill = (tpl: string, v: Vars) => tpl.replace(/\{(\w+)\}/g, (_, k: string) => v[k] ?? '');

class Picker {
  constructor(private seed: string, private variant = 0) {}
  /**
   * Deterministic pick: same source + transform + variant always gives the same text. Each next variant
   * steps every choice to its next option, so "Another phrasing" always changes the wording.
   */
  one<T>(arr: readonly T[], salt: string): T {
    const i = Math.min(arr.length - 1, Math.floor(hash(this.seed + '|' + salt) * arr.length));
    return arr[(i + this.variant) % arr.length];
  }
  some<T>(arr: readonly T[], n: number, salt: string): T[] {
    const scored = arr.map((x, i) => ({ x, k: hash(`${this.seed}|${this.variant}|${salt}|${i}`) }));
    return scored.sort((a, b) => a.k - b.k).slice(0, n).map((o) => o.x);
  }
}

const step = (title: string, body: string, extra: Partial<Step> = {}): Step => ({ id: uid('st-'), title, body, input: 'none', ...extra });

function creativeMedium(topics: string[]): { medium: string; input: Step['input']; collect: string } {
  if (topics.some((t) => t === 'sound' || t === 'music')) return { medium: 'a one-minute soundscape', input: 'audio', collect: 'sounds' };
  if (topics.includes('art')) return { medium: 'a page of quick sketches', input: 'sketch', collect: 'shapes and images' };
  if (topics.some((t) => t === 'writing' || t === 'language')) return { medium: 'an eight-line micro-zine', input: 'text', collect: 'words and phrases' };
  if (topics.includes('code')) return { medium: 'a tiny generative sketch in code', input: 'text', collect: 'rules and patterns' };
  if (topics.some((t) => t === 'food' || t === 'craft')) return { medium: 'a small hands-on object', input: 'photo', collect: 'materials' };
  return { medium: 'a five-photo series', input: 'photo', collect: 'images' };
}

interface Built {
  format: FormatKey;
  title: string;
  summary: string;
  payload: unknown;
  minutes?: number;
  energy?: Energy;
  comfort?: Comfort;
  social?: Social;
  timerMinutes?: number;
  followUps: string[];
}

const stepMinutes = (steps: Step[]) => steps.reduce((n, s) => n + (s.timerMinutes ?? 0), 0);

function build(src: RemixSource, t: RemixTransform, p: Picker): Built {
  const topic = src.topics[0] ? topicLabel(src.topics[0]).toLowerCase() : 'this idea';
  const v: Vars = {
    q: `“${shorten(src.title, 80)}”`,
    short: shorten(src.title),
    topic,
    snippet: firstSentence(src.text) || shorten(src.title, 80),
    question: src.question ?? src.title,
  };
  const f = (tpl: string, extra: Vars = {}) => fill(tpl, { ...v, ...extra });

  switch (t) {
    case 'experiment': {
      const run = p.one([5, 10, 10, 15], 'run');
      const steps: Step[] = [
        step('Make a guess', f(p.one([
          'Before you start, write down what you expect to notice about {q}. Be specific — a number, a feeling, a change.',
          'One sentence before anything else: what do you think will happen when you test {q}?',
          'Write your hunch first. If {q} is true for you, what should you see in the next few minutes?',
        ], 'guess')), { input: 'text' }),
        step('Set it up', f(p.one([
          'Choose one small thing you can change right now that relates to {topic}. Keep everything else the same.',
          'Pick a simple setup: one change, one place, one way of noticing. Write it down so you can repeat it.',
          'Decide what you will change and what you will watch. Small and repeatable beats impressive.',
        ], 'setup'))),
        step('Run it', f(p.one([
          'Spend the next {run} minutes trying it. Stay curious rather than correct.',
          'Give it {run} minutes. Pay attention to anything that shifts, even slightly.',
          'Start the timer and try it for {run} minutes. Resist checking your guess until the end.',
        ], 'run-body'), { run: String(run) }), { timerMinutes: run }),
        step('Observe', p.one([
          'What actually happened? Note anything you didn’t expect.',
          'Describe what you noticed in plain words — facts first, interpretations second.',
          'Write down what changed, what didn’t, and anything odd.',
        ], 'observe'), { input: 'text' }),
        step('Compare', 'How did the result compare with your guess?', { input: 'choice', choices: ['As I expected', 'Partly as expected', 'It surprised me'] }),
      ];
      return {
        format: 'experiment',
        title: f(p.one(['A small experiment: {short}', 'Test it yourself: {short}', '{short} — an experiment', 'Try it out: {short}'], 'title')),
        summary: f(p.one([
          'Turn {q} into a quick test: guess, try, observe, compare.',
          'A hands-on way to check {q} against your own experience.',
          'Find out what {q} looks like in your own day — with a guess to compare against.',
        ], 'summary')),
        payload: { steps } satisfies StepsPayload,
        minutes: stepMinutes(steps) + 5,
        energy: src.energy ?? 2,
        comfort: src.comfort ?? 2,
        followUps: p.some([
          'Repeat it on a different day and compare the results.',
          'Save what you noticed as a Field Note.',
          'Change one variable and run it again.',
          'Write a Version History entry if it changed your mind.',
        ], 2, 'fu'),
      };
    }
    case 'quiz': {
      const opts = (src.extras.length >= 2 ? src.extras : src.topics.map(topicLabel)).filter(Boolean).slice(0, 4);
      const directions = opts.length >= 2 ? opts : ['Why it happens', 'How to try it', 'Who it affects', 'What it changes'];
      const poll = 'There’s no right answer — this is a template poll for noticing your own take.';
      const questions: QuizQuestion[] = [
        { id: uid('qq-'), prompt: f(p.one([
          'How well could you explain {q} to a friend right now?',
          'If someone asked you about {q} today, how confident would you feel?',
        ], 'q1')), options: ['Not yet', 'Roughly', 'Pretty well', 'I could teach it'], explain: poll },
        { id: uid('qq-'), prompt: p.one(['Which direction pulls you most?', 'Where would you go next?', 'Which thread is most interesting to you?'], 'q2'), options: directions, explain: poll },
        { id: uid('qq-'), prompt: f(p.one(['Which statement fits your view best?', 'Be honest — where do you stand on {q}?'], 'q3')), options: [
          `It changed how I see ${topic}`, 'It confirmed what I already thought', 'I’m still unsure', 'I disagree with part of it',
        ], explain: poll },
        { id: uid('qq-'), prompt: p.one(['What would you do next?', 'What feels like the right next step?'], 'q4'), options: [
          'Try it in real life', 'Read or explore more', 'Make something about it', 'Talk to someone about it',
        ], explain: poll },
      ];
      return {
        format: 'quiz',
        title: f(p.one(['Where do you stand? {short}', 'A quick poll: {short}', 'Check your take: {short}'], 'title')),
        summary: f('Four poll questions about {q}. Template questions with no right answers — a way to notice your own view.'),
        payload: { questions } satisfies QuizPayload,
        minutes: 5,
        energy: 1,
        comfort: 1,
        followUps: p.some(['Pick the thread you chose and follow it in a rabbit hole.', 'Try the real-world option you picked.', 'Note your answers in Version History to compare later.'], 2, 'fu'),
      };
    }
    case 'challenge': {
      const go = p.one([10, 15, 20], 'go');
      const steps: Step[] = [
        step('Choose your moment', f(p.one([
          'Pick a time and place today where {q} could actually show up. Write it down.',
          'Where in your ordinary day does {topic} appear? Choose one spot for this challenge.',
        ], 'when')), { input: 'text' }),
        step('Do it', f(p.one([
          'For {go} minutes, live the idea: act on {q} in one small, concrete way.',
          'Spend {go} minutes doing one thing that puts {q} into practice. Keep it small and real.',
          'Go and try it. {go} minutes, one deliberate action, no performance needed.',
        ], 'do'), { go: String(go) }), { timerMinutes: go }),
        step('Notice', p.one(['What did you notice that you would normally miss?', 'What was different from what you expected?', 'Which moment stood out, and why?'], 'notice'), { input: 'text' }),
        step('Capture', p.one(['Take a photo of something that sums it up.', 'Capture one image from the challenge.'], 'capture'), { input: 'photo' }),
      ];
      return {
        format: 'challenge',
        title: f(p.one(['Take it outside the screen: {short}', 'Real-world challenge: {short}', 'Live it for a day: {short}'], 'title')),
        summary: f(p.one(['One small real-world action built from {q}.', 'Move {q} from reading to doing — today.'], 'summary')),
        payload: { steps } satisfies StepsPayload,
        minutes: go + 10,
        energy: src.energy && src.energy > 1 ? src.energy : 2,
        comfort: (Math.min(5, (src.comfort ?? 2) + 1) as Comfort),
        followUps: p.some(['Do it again with someone else and compare.', 'Write what changed in Version History.', 'Turn the photo into a Field Note.'], 2, 'fu'),
      };
    }
    case 'story': {
      const hints = p.some([
        'Start in the middle of the action.',
        'Borrow one small, specific detail from your own experience.',
        'End on a change, not a conclusion.',
        'Use the present tense to make it feel immediate.',
        'Give the character a different age or place than you.',
      ], 3, 'hints');
      return {
        format: 'writing',
        title: f(p.one(['A story from {short}', '{short}, retold as fiction', 'Fiction prompt: {short}'], 'title')),
        summary: f('A story-writing prompt built from {q}. Change the people and the place; keep the feeling.'),
        payload: {
          prompt: f(p.one([
            'Write a short story in which a stranger lives through what you described in {q}. Change the place, keep the feeling.',
            'Turn {q} into a three-scene story: before, the turning point, after. Write it in the third person.',
            'Write a short story told by an object that was there for {q}.',
            'Imagine {q} happened to someone a hundred years ago. Write their afternoon.',
          ], 'prompt')),
          minWords: 150,
          hints,
        } satisfies WritingPayload,
        minutes: 20,
        energy: 2,
        comfort: 2,
        followUps: ['Read it aloud once — then change one line.', 'Save it as a Field Note if you want to keep working on it.'],
      };
    }
    case 'letter': {
      return {
        format: 'writing',
        title: f(p.one(['A letter to future me: {short}', 'Dear future me — {short}', 'Note to my future self: {short}'], 'title')),
        summary: f('Write to yourself a year from now about {q}. Seal it as a capsule to reopen later.'),
        payload: {
          prompt: f(p.one([
            'Write a letter to yourself a year from now about {q}. What do you hope will have changed? What do you suspect won’t?',
            'Dear future me — explain {q} as you see it today, then ask your future self one honest question.',
            'Write to the person you’ll be next year. Tell them what {q} means to you now, and one thing to check on.',
          ], 'prompt')),
          minWords: 80,
          hints: p.some([
            'Include one prediction you can check later.',
            'Mention something ordinary about today — it will be the most surprising part later.',
            'Ask your future self a question you can’t answer yet.',
            'Be kind; you are writing to someone you’ll become.',
          ], 3, 'hints'),
        } satisfies WritingPayload,
        minutes: 15,
        energy: 1,
        comfort: 1,
        followUps: ['Seal the letter as a capsule (Create → Capsules) so you can reopen it later.'],
      };
    }
    case 'debate': {
      const lens = src.extras.length ? p.one(src.extras, 'lens') : undefined;
      return {
        format: 'debate',
        title: f(p.one(['Argue both sides: {short}', 'For, against, and a third way: {short}', 'Switch perspective: {short}'], 'title')),
        summary: f('A perspective debate built from {q}. The sides are prompts for you to argue — not arguments written for you.'),
        payload: {
          question: f(p.one([
            'What is the strongest case for and against how you see {q}?',
            'Would someone who disagrees with you see {q} differently — and would they have a point?',
            'Is the way you think about {q} the only reasonable way to see it?',
          ], 'question')),
          sides: [
            { label: 'The case for', argument: p.one(['Argue for your current view as convincingly as you can. What is your best evidence?', 'Make the strongest case for how you see it now — reasons, not just feelings.'], 'for') },
            { label: 'The case against', argument: p.one(['Argue against yourself. What would a thoughtful critic say you are missing?', 'Steel-man the opposite view: argue it as if you believed it.'], 'against') },
            { label: lens ? `Through “${shorten(lens, 30)}”` : 'A third view', argument: lens ? `Look at it through the lens of “${lens}”. What does that angle notice that both sides miss?` : 'Look for a position neither side has considered. What would someone from a different place or generation say?' },
          ],
        } satisfies DebatePayload,
        minutes: 15,
        energy: 2,
        comfort: 3,
        followUps: ['Record whether your thinking changed in Version History.', 'Try it as a conversation with someone you trust.'],
      };
    }
    case 'realworld': {
      const ideas = src.extras.length ? src.extras : [`Use ${src.title.toLowerCase()} to help someone with something small`];
      const main = p.one(ideas, 'idea');
      const others = ideas.filter((x) => x !== main).slice(0, 2);
      const go = p.one([15, 20, 25], 'go');
      const steps: Step[] = [
        step('Pick your challenge', `Today’s challenge: ${main}${others.length ? `\n\nOr, if that doesn’t fit today:\n${others.map((o) => `• ${o}`).join('\n')}` : ''}`),
        step('Prepare', p.one(['Gather what you need in under five minutes. Keep it simple.', 'Set up the smallest version you can start right now.'], 'prep')),
        step('Do it', f(p.one(['Spend {go} minutes on it for real — not practice, the actual thing.', 'Give it {go} focused minutes in the real world.'], 'do'), { go: String(go) }), { timerMinutes: go }),
        step('Reflect', p.one(['What worked? What would you change next time?', 'What did doing it for real teach you that practice didn’t?'], 'reflect'), { input: 'text' }),
      ];
      return {
        format: 'challenge',
        title: f(p.one(['Use {short} for real', '{short}, out in the world', 'A real-world {short} challenge'], 'title')),
        summary: `A real-world challenge for ${src.title}, picked from the skill’s own list of real-world uses.`,
        payload: { steps } satisfies StepsPayload,
        minutes: go + 10,
        energy: 2,
        comfort: 3,
        followUps: ['Log it as practice on the skill page.', 'Save a photo or note of the result.'],
      };
    }
    case 'project': {
      const sk = src.skillId ? getSkill(src.skillId) : undefined;
      const goal = sk?.levels.length ? p.one(sk.levels.map((l) => l.goal), 'goal') : src.text;
      const steps: Step[] = [
        step('Decide what you’ll make', `Aim for something small you could finish today.${goal ? `\n\nA direction to start from: ${goal}` : ''}`, { input: 'text' }),
        step('Gather', p.one(['Collect what you need — tools, materials, references. Five minutes, no shopping trips.', 'Lay out everything you need before you start.'], 'gather')),
        step('Make a first version', p.one(['Make a rough first version. Done beats perfect.', 'Build the quickest possible version, start to finish.'], 'make'), { timerMinutes: 20 }),
        step('Improve one thing', 'Pick the weakest part and improve only that.', { timerMinutes: 10 }),
        step('Look back', p.one(['Take a photo of what you made.', 'Capture the result — a photo is enough.'], 'look'), { input: 'photo' }),
      ];
      return {
        format: 'project',
        title: f(p.one(['A small {short} project', 'Make something: {short}', 'Weekend project: {short}'], 'title')),
        summary: `A hands-on ${src.title.toLowerCase()} project: first version, one improvement, then look back.`,
        payload: { steps } satisfies StepsPayload,
        minutes: stepMinutes(steps) + 10,
        energy: 2,
        comfort: 2,
        followUps: ['Share it with a friend from the Builder.', 'Add it to “Projects I want to try” if you want to go further.'],
      };
    }
    case 'creative': {
      const m = creativeMedium(src.topics);
      const make = p.one([15, 20], 'make');
      const steps: Step[] = [
        step('Collect', f(p.one([
          `Gather five ${m.collect} that connect to {q} — from around you, from memory, or from your notes.`,
          `Spend a few minutes collecting ${m.collect} that remind you of {q}.`,
        ], 'collect'))),
        step('Make', f(`Make ${m.medium} that responds to {q}. Don’t explain the idea — let the piece hint at it.`), { timerMinutes: make, input: m.input }),
        step('Title it', 'Give it a title that adds something the piece doesn’t say.', { input: 'text' }),
        step('Look back', p.one(['What did making it show you that reading didn’t?', 'What surprised you while making it?'], 'look'), { input: 'text' }),
      ];
      return {
        format: 'project',
        title: f(p.one([`Make ${m.medium}: {short}`, '{short} — a creative response', `Respond with ${m.medium}: {short}`], 'title')),
        summary: f(`A creative project: make ${m.medium} in response to {q}.`),
        payload: { steps } satisfies StepsPayload,
        minutes: make + 15,
        energy: 2,
        comfort: 3,
        followUps: ['Keep it as a Field Note.', 'Seal it in a capsule and see how it feels in a year.'],
      };
    }
    case 'outdoor': {
      const walk = p.one([15, 20, 30], 'walk');
      const steps: Step[] = [
        step('Carry the question', f(p.one([
          'Take this question outside with you: {question}',
          'Before you leave, read this once and keep it in mind: {question}',
        ], 'carry'))),
        step('Walk', f(p.one([
          'Walk somewhere ordinary for {walk} minutes. Look for three things that connect to {topic}.',
          'Go for a {walk}-minute walk. Every few minutes, stop and look for evidence related to the question.',
        ], 'walk'), { walk: String(walk) }), { timerMinutes: walk }),
        step('Collect evidence', 'Photograph one thing that answers — or complicates — the question.', { input: 'photo' }),
        step('Write it down', p.one(['What did the street, park or room tell you?', 'What did you find that you wouldn’t have looked for otherwise?'], 'write'), { input: 'text' }),
      ];
      return {
        format: 'outdoor',
        title: f(p.one(['A walk with a question: {short}', 'Go looking for {topic}', 'Field trip: {short}'], 'title')),
        summary: f('Take {q} outside and look for evidence on a short walk.'),
        payload: { steps } satisfies StepsPayload,
        minutes: walk + 10,
        energy: 2,
        comfort: 2,
        followUps: ['Pin what you found on the Curiosity Map by linking the note.', 'Try the same walk at a different time of day.'],
      };
    }
    case 'prompt': {
      return {
        format: 'writing',
        title: f(p.one(['Write from a note: {short}', 'Keep going: {short}', '{short} — a writing prompt'], 'title')),
        summary: f('A writing prompt grown from your field note {q}.'),
        payload: {
          prompt: f(p.one([
            'Start from your note {q} and write for ten minutes without stopping. Where does it lead?',
            'Rewrite your note {q} from the point of view of someone who disagrees with it.',
            'Expand {q} into a short piece: what happened just before, and what happened next?',
            'Use {q} as the first line of a letter to someone who wasn’t there.',
          ], 'prompt')),
          minWords: 120,
          hints: p.some(['Don’t edit while you write.', 'Use one sensory detail per paragraph.', 'Finish with a question.', 'Keep your original note open beside you.'], 3, 'hints'),
        } satisfies WritingPayload,
        minutes: 15,
        energy: 1,
        comfort: 1,
        followUps: ['Save the piece as a new Field Note linked to the original.'],
      };
    }
    case 'duo': {
      const mins = Math.max(10, Math.min(60, src.minutes ?? 20));
      const steps: Step[] = [
        step('Invite someone', f(p.one([
          'Pick one person and agree on a time. You will each do this separately: {snippet}',
          'Ask a friend, partner or neighbour to join. The plan — each of you, on your own: {snippet}',
        ], 'invite'))),
        step('Do it separately', `Each of you does it on your own — about ${mins} minutes. No comparing yet.`, { timerMinutes: mins }),
        step('Compare interpretations', p.one(['What did each of you notice? Where did your interpretations differ?', 'Swap stories. What did they see that you missed?'], 'compare'), { input: 'text' }),
        step('Make one thing together', p.one([
          'Combine your experiences into one small thing — a photo pair, a shared list, a two-line poem.',
          'Make one shared artefact from both versions: two photos side by side, or one sentence each.',
        ], 'make'), { input: 'photo' }),
      ];
      return {
        format: 'collab',
        title: f(p.one(['Two-person quest: {short}', 'Together: {short}', 'Side by side: {short}'], 'title')),
        summary: 'A plot twist turned into a two-person quest: do it separately, then compare and make something together.',
        payload: { steps } satisfies StepsPayload,
        minutes: mins + 15,
        energy: src.energy ?? 2,
        comfort: src.comfort ?? 2,
        social: 'shared',
        followUps: ['Share it for friends from the Builder — they import it with a code; no server is involved.'],
      };
    }
  }
}

/**
 * Build a draft Experience from a source using rule-based templates.
 * `variant` picks a different phrasing for the same source + transformation.
 * Throws if the source can't be found.
 */
export function remix(source: Ref, transform: RemixTransform, variant = 0): Experience {
  const src = remixSource(source);
  if (!src) throw new Error('That item is no longer available to remix.');
  const p = new Picker(`${source.kind}:${source.id}:${transform}`, Math.max(0, Math.floor(variant)));
  const b = build(src, transform, p);
  const fmtNote = REMIX_OPTIONS[transform].label.toLowerCase();
  return {
    id: uid('rx-'),
    title: b.title,
    summary: `${b.summary} Template-generated ${fmtNote} remix.`,
    area: src.area,
    format: b.format,
    topics: src.topics.slice(0, 4),
    minutes: Math.max(1, Math.round(b.minutes ?? src.minutes ?? 15)),
    energy: b.energy ?? src.energy ?? 2,
    comfort: b.comfort ?? src.comfort ?? 2,
    cost: src.cost ?? 0,
    social: b.social ?? (src.social === 'shared' ? 'shared' : 'solo'),
    origin: 'remix',
    payload: b.payload,
    timerMinutes: b.timerMinutes,
    skillId: src.skillId,
    followUps: b.followUps,
    createdAt: nowISO(),
    visibility: 'private',
    remixOf: { kind: source.kind, id: source.id },
  };
}
